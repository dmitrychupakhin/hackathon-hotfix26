const banner = "// Generated by npm run api:generate. Do not edit.\n";
function sourceFile(source: string) {
  return ts.createSourceFile(
    "generated.ts",
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
}

function inspectRtk(source: string) {
  const types: string[] = [];
  const hooks: string[] = [];
  const endpoints: string[] = [];
  const visit = (node: ts.Node) => {
    if (
      ts.isTypeAliasDeclaration(node) &&
      node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    )
      types.push(node.name.text);
    if (
      ts.isVariableDeclaration(node) &&
      ts.isObjectBindingPattern(node.name)
    ) {
      for (const element of node.name.elements)
        if (
          ts.isIdentifier(element.name) &&
          element.name.text.startsWith("use")
        )
          hooks.push(element.name.text);
    }
    if (
      ts.isPropertyAssignment(node) &&
      ts.isCallExpression(node.initializer) &&
      ts.isPropertyAccessExpression(node.initializer.expression) &&
      node.initializer.expression.expression.getText() === "build"
    )
      endpoints.push(node.name.getText().replaceAll('"', ""));
    ts.forEachChild(node, visit);
  };
  visit(sourceFile(source));
  return { types, hooks, endpoints };
}

function inspectSdk(source: string) {
  const operations: { name: string; dataType: string; optional: boolean }[] =
    [];
  for (const statement of sourceFile(source).statements) {
    if (
      !ts.isVariableStatement(statement) ||
      !statement.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    )
      continue;
    for (const declaration of statement.declarationList.declarations) {
      if (
        !ts.isIdentifier(declaration.name) ||
        !declaration.initializer ||
        !ts.isArrowFunction(declaration.initializer)
      )
        continue;
      const parameter = declaration.initializer.parameters[0];
      if (!parameter?.type || !ts.isTypeReferenceNode(parameter.type)) continue;
      const dataType = parameter.type.typeArguments?.[0]?.getText();
      if (!dataType)
        throw new Error(
          `Missing SDK options type for ${declaration.name.text}`,
        );
      operations.push({
        name: declaration.name.text,
        dataType,
        optional: Boolean(parameter.questionToken),
      });
    }
  }
  return operations;
}

async function filesIn(root: string): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(root, { withFileTypes: true })) {
    const path = join(root, entry.name);
    if (entry.isDirectory()) files.push(...(await filesIn(path)));
    else files.push(path);
  }
  return files;
}

export async function generateApiArtifacts(
  schema: unknown,
  temporary: string,
  report = analyzeApiModules(schema, apiModules),
) {
  if (!report.valid) throw new Error(formatApiModuleReport(report));
  const counts = report.counts;
  const schemaTags = renderSchemaTags(report.tags);
  const schemaFile = join(temporary, "schema.json");
  const staged = join(temporary, "artifacts");
  await writeFile(schemaFile, JSON.stringify(schema));
  const { createClient } = await import("@hey-api/openapi-ts");
  for (const module of Object.keys(apiModules) as ApiModule[]) {
    const folder = join(staged, module);
    await mkdir(folder, { recursive: true });
    const rtkSource = await generateEndpoints({
      schemaFile,
      apiFile: "../../base-api.ts",
      apiImport: "baseApi",
      exportName: `generated${module[0].toUpperCase()}${module.slice(1)}Api`,
      hooks: { queries: true, lazyQueries: true, mutations: true },
      tag: false,
      filterEndpoints: (name, { operation }) =>
        moduleForTags(operation.tags, name, apiModules) === module,
    });
    if (typeof rtkSource !== "string")
      throw new Error(`Missing RTK source for ${module}`);
    const rtk = inspectRtk(rtkSource);
    if (rtk.endpoints.length !== counts[module])
      throw new Error(`Incomplete RTK generation for ${module}`);
    await writeFile(join(folder, "rtk.ts"), banner + rtkSource);

    const moduleSchemaFile = join(temporary, `${module}.json`);
    await writeFile(
      moduleSchemaFile,
      JSON.stringify(schemaForModule(schema, report, module)),
    );
    await createClient({
      input: moduleSchemaFile,
      output: join(folder, "sdk"),
      plugins: [
        "@hey-api/typescript",
        { name: "@hey-api/client-next", throwOnError: true },
        {
          name: "@hey-api/sdk",
          client: "@hey-api/client-next",
          operations: { strategy: "flat" },
        },
      ],
    });
    const zodSchemaFile = join(temporary, `${module}-zod.json`);
    await writeFile(
      zodSchemaFile,
      JSON.stringify(schemaForZod(schemaForModule(schema, report, module))),
    );
    await createClient({
      input: zodSchemaFile,
      output: join(folder, "schemas"),
      plugins: [{ name: "zod", compatibilityVersion: 4 }],
    });
    const sdkSource = await readFile(join(folder, "sdk/sdk.gen.ts"), "utf8");
    const sdk = inspectSdk(sdkSource);
    if (
      sdk.length !== counts[module] ||
      sdk.some((operation) => !rtk.endpoints.includes(operation.name))
    )
      throw new Error(`SDK and RTK operations differ for ${module}`);

    let configured = false;
    try {
      await access(join(apiRoot, module, `${module}-api.ts`));
      configured = true;
    } catch {
      /* No custom cache configuration for this group. */
    }
    const apiName = `${module}Api`;
    const generatedName = `generated${module[0].toUpperCase()}${module.slice(1)}Api`;
    const apiImport = configured
      ? `{ ${apiName} } from "../../${module}/${module}-api"`
      : `{ ${generatedName} as ${apiName} } from "./rtk"`;
    await writeFile(
      join(folder, "client.ts"),
      `${banner}import ${apiImport};\nexport { ${apiName} };\nexport * from "./schemas/zod.gen";\nexport type { ${rtk.types.join(", ")} } from "./rtk";\nexport const { ${rtk.hooks.join(", ")} } = ${apiName};\n`,
    );

    const title = module[0].toUpperCase() + module.slice(1);
    const methods = sdk
      .map(
        ({ name, dataType, optional }) =>
          `    ${name}: async (options${optional ? "?" : ""}: ServerOptions<Options<Types.${dataType}, true>>) => (await sdk.${name}({ ...options, client, throwOnError: true })).data,`,
      )
      .join("\n");
    await writeFile(
      join(folder, "server.ts"),
      `${banner}import "server-only";\nimport { getServerRequestConfig } from "../../server-request-config";\nimport type { ServerOptions } from "../../server-transport";\nimport { createClient } from "./sdk/client";\nimport * as sdk from "./sdk/sdk.gen";\nimport type { Options } from "./sdk/sdk.gen";\nimport type * as Types from "./sdk/types.gen";\nexport { ServerApiError } from "../../server-transport";\nexport type * from "./sdk/types.gen";\nexport async function get${title}ServerApi() {\n  const client = createClient(await getServerRequestConfig());\n  return {\n${methods}\n  };\n}\n`,
    );
    await writeFile(
      join(folder, "manifest.json"),
      `${JSON.stringify({ endpoints: rtk.endpoints, hooks: rtk.hooks, serverMethods: sdk.map(({ name }) => name) }, null, 2)}\n`,
    );
  }
  await writeFile(join(staged, "schema-tags.ts"), schemaTags);
  await writeFile(
    join(staged, "README.md"),
    "# Generated API\n\nEverything in this directory is generated by `npm run api:generate`.\nDo not edit manually. `npm run api:clean` removes this entire directory.\nHand-maintained public entry points and cache/transport configuration live outside.\nschema-tags.ts refreshes before mapping validation; a failed mapping check preserves API code but updates this diagnostic snapshot.\n",
  );
  // Make the server-only boundary explicit even for accidental direct SDK imports.
  const files = await filesIn(staged);
  for (const file of files) {
    if (file.includes("/sdk/") && file.endsWith(".ts")) {
      await writeFile(
        file,
        `${banner}import "server-only";\n${await readFile(file, "utf8")}`,
      );
    }
  }
  return {
    counts,
    files: await Promise.all(
      files.map(async (file) => ({
        path: relative(staged, file),
        content: await readFile(file, "utf8"),
      })),
    ),
  };
}

export async function generateAndPublishApi(schema: unknown, root = apiRoot) {
  // Read and validate the shape before touching even the diagnostic snapshot.
  const report = analyzeApiModules(schema, apiModules);
  await publishSchemaTags(renderSchemaTags(report.tags), root);
  console.log(formatApiModuleReport(report));
  if (!report.valid) {
    throw new Error(
      "Генерация API остановлена: исправьте apiModules или контракт. Снимок тегов обновлён, прежний код API не изменён.",
    );
  }
  const typeErrors = apiModuleTypeErrors();
  if (typeErrors.length)
    throw new Error(
      `Проверка типов apiModules не пройдена:\n${typeErrors.join("\n")}`,
    );
  const temporary = await mkdtemp(join(tmpdir(), "openapi-clients-"));
  try {
    const result = await generateApiArtifacts(schema, temporary, report);
    const rows = (Object.keys(apiModules) as ApiModule[]).map((module) => {
      const manifestFile = result.files.find(
        (file) => file.path === `${module}/manifest.json`,
      );
      if (!manifestFile)
        throw new Error(`Missing generated manifest for ${module}`);
      const manifest = JSON.parse(manifestFile.content) as {
        endpoints: string[];
        serverMethods: string[];
      };
      return {
        Группа: module,
        Тег: apiModules[module],
        "В схеме": result.counts[module],
        "RTK endpoints": manifest.endpoints.length,
        "SDK методы": manifest.serverMethods.length,
      };
    });
    await publishGeneratedApi(result.files, root);
    console.table(rows);
    console.log(
      `Сгенерировано: групп ${rows.length}/${report.groupCount}; RTK endpoints ${rows.reduce((sum, row) => sum + row["RTK endpoints"], 0)}/${report.operations.length}; SDK методов ${rows.reduce((sum, row) => sum + row["SDK методы"], 0)}/${report.operations.length}; записано файлов: ${result.files.length}.`,
    );
    return result.counts;
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}
