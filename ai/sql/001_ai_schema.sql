-- Run by the backend/deployment database owner, NOT by AI application startup.
-- Execute in the SAME PostgreSQL database as Django. No Django tables are changed.
BEGIN;
CREATE SCHEMA IF NOT EXISTS ai;
CREATE TABLE IF NOT EXISTS ai.schema_version (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    version integer NOT NULL
);
INSERT INTO ai.schema_version(singleton,version) VALUES (true,1)
ON CONFLICT(singleton) DO NOTHING;
CREATE TABLE IF NOT EXISTS ai.objects (
    kind text NOT NULL,
    id text NOT NULL,
    owner text NOT NULL,
    data jsonb NOT NULL CHECK (jsonb_typeof(data)='object'),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(kind,id)
);
CREATE INDEX IF NOT EXISTS ai_objects_owner ON ai.objects(owner,kind,created_at DESC);
CREATE TABLE IF NOT EXISTS ai.events (
    seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id text NOT NULL,
    type text NOT NULL,
    data jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ai_events_run ON ai.events(run_id,seq);
-- Backend owns source registration. relative_path is below AI_SOURCE_ROOT (read-only volume).
-- Update version + sha256 whenever bytes change. Never reuse a version for different bytes.
CREATE TABLE IF NOT EXISTS ai.files (
    owner text NOT NULL,
    id text NOT NULL,
    version text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    filename text NOT NULL,
    relative_path text NOT NULL,
    sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
    media_type text NOT NULL DEFAULT 'application/octet-stream',
    PRIMARY KEY(owner,id)
);
COMMIT;
